import { test } from 'node:test';
import assert from 'node:assert';

import {
    Marker,
    HBPSerializer,
} from '../dist/src/index.js';

const serializer = new HBPSerializer();

test('serializeNull', () => {
    assert.deepStrictEqual(serializer.serialize(null), new Uint8Array([0x01, 0x00]));
});

test('serializeBool', () => {
    assert.deepStrictEqual(serializer.serialize(false), new Uint8Array([0x01, 0x01]));
    assert.deepStrictEqual(serializer.serialize(true), new Uint8Array([0x01, 0x02]));
});

test('serializeInt (Big Endian)', () => {
    // These values are adapted to Big Endian (Network Byte Order)
    const cases = [
        [45n, Marker.signed_int_8, [0x01, 0x10, 0x2D]],
        [6347n, Marker.signed_int_16, [0x01, 0x11, 0x18, 0xCB]],
        [9123424n, Marker.signed_int_32, [0x01, 0x12, 0x00, 0x8B, 0x36, 0x60]],
        [5294967295n, Marker.signed_int_64, [0x01, 0x13, 0x00, 0x00, 0x00, 0x01, 0x3B, 0x9A, 0xC9, 0xFF]],

        [28446744073709551615n, Marker.signed_int_128, [
            0x01, 0x14,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
            0x8A, 0xC7, 0x23, 0x04, 0x89, 0xE7, 0xFF, 0xFF
        ]],

        [340282366920938463463375607431768211456n, Marker.signed_int_256, [
            0x01, 0x15,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x03, 0x8D, 0x7E, 0xA4, 0xC6, 0x80, 0x00
        ]],

        [115792089237316395423570985008687907853269984665640564039457584007913129639935n, Marker.signed_int_512, [
            0x01, 0x16,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x7C, 0x75,
            0xD6, 0x95, 0xC2, 0x70, 0x6A, 0xC5, 0xE9, 0x70,
            0x44, 0xC3, 0xB2, 0xD3, 0xEF, 0x59, 0x29, 0x94,
            0x7F, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF
        ]],

        [30n, Marker.signed_int_arbitrary, [0x01, 0x1F, 0x00, 0x01, 0x1E]],
        [9123424n, Marker.signed_int_arbitrary, [0x01, 0x1F, 0x00, 0x03, 0x8B, 0x36, 0x60]],
        [5294967295n, Marker.signed_int_arbitrary, [0x01, 0x1F, 0x00, 0x05, 0x01, 0x3B, 0x9A, 0xC9, 0xFF]],

        [250n, Marker.unsigned_int_8, [0x01, 0x20, 0xFA]],
        [6347n, Marker.unsigned_int_16, [0x01, 0x21, 0x18, 0xCB]],
        [9123424n, Marker.unsigned_int_32, [0x01, 0x22, 0x00, 0x8B, 0x36, 0x60]],
        [5294967295n, Marker.unsigned_int_64, [0x01, 0x23, 0x00, 0x00, 0x00, 0x01, 0x3B, 0x9A, 0xC9, 0xFF]],
    ];

    for (let [value, type, expected] of cases) {
        const result = serializer.serializeValue(value, type);
        assert.deepStrictEqual(result, new Uint8Array(expected), `Failed for value ${value} (${type})`);
    }
});

test('serializeString', () => {
    const cases = [
        ["Hello World", [0x01, 0x6B, 0x48, 0x65, 0x6C, 0x6C, 0x6F, 0x20, 0x57, 0x6F, 0x72, 0x6C, 0x64]],
    ];

    for (let [str, expected] of cases) {
        const result = serializer.serialize(str);
        assert.deepStrictEqual(result, new Uint8Array(expected), `Failed for string "${str}"`);
    }
});

import { test } from 'node:test';
import assert from 'node:assert';

import {
    serializeNull,
    serializeBool,
    serializeInt,
    serializeString,
    Marker,
} from '../dist/src/index.js';

test('serializeNull', () => {
    assert.deepStrictEqual(serializeNull(), Buffer.from([0x01, 0x00]));
});

test('serializeBool', () => {
    assert.deepStrictEqual(serializeBool(false), Buffer.from([0x01, 0x01]));
    assert.deepStrictEqual(serializeBool(true), Buffer.from([0x01, 0x02]));
});


test('serializeString', () => {
    const cases = [
        ["Hello World", [0x01, 0xE0, 0x8B, 0x48, 0x65, 0x6C, 0x6C, 0x6F, 0x20, 0x57, 0x6F, 0x72, 0x6C, 0x64]],
    ];

    for (let [str, expected] of cases) {
        const result = serializeString(str, 20);
        assert.deepStrictEqual(result, Buffer.from(expected), `Failed for string "${str}"`);
    }
});


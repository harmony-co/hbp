// Parser tests
import { test } from 'node:test';
import assert from 'node:assert';

import {
    HBPParser,
} from '../dist/src/index.js';

test('parseBool', () => {
    assert.strictEqual(new HBPParser(new Uint8Array([0x01, 0x01])).parse(), false);
    assert.strictEqual(new HBPParser(new Uint8Array([0x01, 0x02])).parse(), true);
});

test('parseInt (Big Endian)', () => {
    const cases = [
        [0x01, 0x10, 0x2D], // i8
        [0x01, 0x11, 0x18, 0xCB], // i16
        [0x01, 0x12, 0x00, 0x8B, 0x36, 0x60], // i32
        [0x01, 0x13, 0x00, 0x00, 0x00, 0x01, 0x3B, 0x9A, 0xC9, 0xFF], // i64

        // i128
        [0x01, 0x14, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x8A, 0xC7, 0x23, 0x04, 0x89, 0xE7, 0xFF, 0xFF],

        // i256
        [0x01, 0x15, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03, 0x8D, 0x7E, 0xA4, 0xC6, 0x80, 0x00],

        // unsigned
        [0x01, 0x20, 0xFA], // u8
        [0x01, 0x21, 0x18, 0xCB], // u16
        [0x01, 0x22, 0x00, 0x8B, 0x36, 0x60], // u32
        [0x01, 0x23, 0x00, 0x00, 0x00, 0x01, 0x3B, 0x9A, 0xC9, 0xFF], // u64
    ];

    const expected = [
        45n,
        6347n,
        9123424n,
        5294967295n,
        28446744073709551615n,
        340282366920938463463375607431768211456n,

        // unsigned
        250n,
        6347n,
        9123424n,
        5294967295n,
    ];

    for (let i = 0; i < cases.length; i++) {
        const result = new HBPParser(new Uint8Array(cases[i])).parse();
        // result will be a bigint if it's parsed as an int.
        assert.strictEqual(BigInt(result), expected[i], `Case ${i} failed`);
    }
});

test("parseString", () => {
    const cases = [
        [0x01, 0x6B, 0x48, 0x65, 0x6C, 0x6C, 0x6F, 0x20, 0x57, 0x6F, 0x72, 0x6C, 0x64],
    ];

    const expected = [
        "Hello World",
    ];

    for (let i = 0; i < cases.length; i++) {
        const result = new HBPParser(new Uint8Array(cases[i])).parse();
        assert.strictEqual(result, expected[i], `Case ${i} failed`);
    }
});

test("parseStringCounter (Negative Tests)", () => {
    // Test invalid markers
    assert.throws(() => {
        new HBPParser(new Uint8Array(
            // 0xAA is undefined in our spec
            [0x01, 0xAA, 0x20, 0x48, 0x65, 0x6C, 0x6C, 0x6F, 0x20, 0x57, 0x6F, 0x72, 0x6C, 0x64]
        )).parse()
    }, /Unknown or Unimplemented Marker: 0xaa/i);
});
